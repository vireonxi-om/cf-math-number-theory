#include <bits/stdc++.h>
using namespace std;
typedef long long ll;
int n, m, i, j;

void solve(){
    scanf("%d%d%d%d", &n, &m, &i, &j);
    printf("%d %d %d %d\n", 1, 1, n, m);
}

int main(){
    int t;
    scanf("%d", &t);
    while(t--) solve();
    return 0;
}